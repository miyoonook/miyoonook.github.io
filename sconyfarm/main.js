function renderMods(data) {
  const container = document.querySelector(".body-wrap");
  if (!container) return;

  container.innerHTML = "";

  data.forEach((section) => {
    const sectionEl = document.createElement("div");
    sectionEl.className = "mods-section d-flex mt-5";
    sectionEl.innerHTML = `
      <div class="s-icon"></div>
      <div class="s-title d-flex">${section.category}</div>
    `;

    const gridEl = document.createElement("div");
    gridEl.className = "mods-grid";

    const itemsHTML = section.items
      .map((item) => {
        const hasTrans = Boolean(item.transLink && item.transLink.trim() !== "");
        const transClass = hasTrans ? "enabled" : "disabled";
        const transHref = hasTrans ? item.transLink : "javascript:void(0);";
        const transTarget = hasTrans ? 'target="_blank" rel="noopener noreferrer"' : "";

        return `
        <div class="mods-list">
          <div class="keyword">${item.keyword || ""}</div>
          <div class="name mt-1">${item.title || ""}</div>
          <div class="description mt-1">${item.description || ""}</div>
          <div class="btn-download mt-3">
            <a href="${item.link || "#"}" target="_blank" rel="noopener noreferrer">모드 다운로드</a>
          </div>
          <div class="btn-translation mt-2">
            <a href="${transHref}" class="${transClass}" ${transTarget}>한국어 번역</a>
          </div>
        </div>
      `;
      })
      .join("");

    gridEl.innerHTML = itemsHTML;

    container.appendChild(sectionEl);
    container.appendChild(gridEl);
  });
}

document.addEventListener("DOMContentLoaded", () => {
  renderMods(modData);
});
